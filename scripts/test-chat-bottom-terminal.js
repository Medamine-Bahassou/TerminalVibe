const fs = require('fs'), path = require('path');
if (!process.versions.electron) {
  const r = require('child_process').spawnSync(require('electron'), [__filename, '--no-sandbox'], { stdio: 'inherit', env: { ...process.env, ELECTRON_RUN_AS_NODE: '' } });
  process.exit(r.status ?? 1);
}
const { app, BrowserWindow } = require('electron');
const timeout = setTimeout(() => app.exit(1), 20000);
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false });
  await win.loadURL('about:blank');
  await win.webContents.insertCSS(fs.readFileSync(path.join(__dirname, '..', 'workspace.css'), 'utf8'));
  const source = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
  const helpers = source.slice(source.indexOf('  function disposeChatBottomTerminal('), source.indexOf('  // An agent finished its turn:'));
  console.log(await win.webContents.executeJavaScript(`(async () => {
    const check = (ok, msg) => { if (!ok) throw Error(msg); };
    const owner = { id: 'chat', threadHistory: true, el: document.createElement('div'), term: { focus: () => focused = 'chat' } };
    owner.el.style.cssText = 'position:relative;height:400px';
    document.body.append(owner.el);
    let focused, created = 0, disposed = 0, fits = 0, wsReady = true;
    const controls = [], wsp = {}, uuid = () => 'shell', chatCwd = () => '/project/chat';
    const activeTerminal = () => owner, focusSlot = () => {};
    const findTermById = () => ({ ws: wsp });
    const sendControl = msg => controls.push(msg), fitTerm = () => { fits++; };
    const _termFitObserver = { observe() {}, unobserve() {} }, _disposeTermRenderers = () => {};
    const buffer = { viewportY: 0, baseY: 0, cursorY: 0 };
    const _createTermEntry = () => { created++; return { id: 'shell', term: { cols: 80, rows: 24, buffer: { active: buffer }, open() {}, focus() { focused = 'shell'; }, dispose() { disposed++; } } }; };
    ${helpers}
    const press = () => document.dispatchEvent(new KeyboardEvent('keydown', { key: 'j', ctrlKey: true, bubbles: true, cancelable: true }));
    press(); await new Promise(requestAnimationFrame);
    check(created === 1 && focused === 'shell', 'Ctrl+J did not open and focus shell');
    check(controls[0].cwd === '/project/chat', 'Shell did not start in chat project');
    const sash = owner._bottomTerminal.el.querySelector('[role="separator"]');
    const panel = owner._bottomTerminal.el, screen = panel.querySelector('.chat-bottom-screen'), body = screen.parentElement;
    const screenTop = () => screen.getBoundingClientRect().top - body.getBoundingClientRect().top;
    const startFits = fits, startHeight = screen.offsetHeight;
    const size = () => owner.el.style.getPropertyValue('--chat-terminal-height');
    sash.setPointerCapture = () => {}; // Synthetic pointer events don't register an active browser pointer.
    const pointer = (type, clientY) => sash.dispatchEvent(new PointerEvent(type, { pointerId: 1, clientY, bubbles: true, cancelable: true }));
    pointer('pointerdown', 260);
    pointer('pointermove', 210);
    pointer('pointermove', 180);
    check(size() === '35%', 'Pointer events changed layout before the next frame');
    await new Promise(requestAnimationFrame);
    check(size() === '55%' && screen.offsetHeight === startHeight && fits === startFits, 'Drag resized or refit the live screen before release');
    check(screenTop() === 0, 'Growing the divider separated a top-row prompt from the top of the terminal');
    pointer('pointerup', 180);
    check(size() === '55%' && sash.getAttribute('aria-valuenow') === '55', 'Dragging did not increase the terminal height');
    check(fits === startFits + 1 && screen.offsetHeight > startHeight, 'Release did not fit the terminal at the final size');
    sash.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowDown', bubbles: true, cancelable: true }));
    check(size() === '50%', 'Keyboard could not resize the terminal');
    press(); check(owner._bottomTerminal.el.hidden && focused === 'chat', 'Ctrl+J did not hide shell and restore chat focus');
    press(); await new Promise(requestAnimationFrame);
    check(created === 1 && !owner._bottomTerminal.el.hidden, 'Reopen created another shell');
    check(size() === '50%', 'Reopen lost the resized height');
    pointer('pointerdown', 200);
    pointer('pointermove', 390);
    await new Promise(requestAnimationFrame);
    check(screenTop() === 0, 'Shrinking clipped the top-row prompt during the drag');
    pointer('pointerup', 390);
    check(size() === '10%', 'Dragging did not reach the smaller minimum height');
    for (const key of ['ArrowUp', 'Home']) sash.dispatchEvent(new KeyboardEvent('keydown', { key, bubbles: true, cancelable: true }));
    check(size() === '10%', 'Home did not restore the minimum height');
    sash.dispatchEvent(new KeyboardEvent('keydown', { key: 'End', bubbles: true, cancelable: true }));
    buffer.cursorY = 23;
    const gridHeight = body.clientHeight;
    pointer('pointerdown', 100);
    pointer('pointermove', 180);
    await new Promise(requestAnimationFrame);
    check(Math.abs(screenTop() + gridHeight - body.clientHeight) < 2, 'Shrinking clipped a cursor on the last row');
    pointer('pointerup', 180);
    owner._cliView = true; press(); check(!owner._bottomTerminal.el.hidden, 'Shortcut affected CLI view');
    owner._cliView = false; owner._bottomTerminal.el.querySelector('button').click();
    check(owner._bottomTerminal.el.hidden, 'Close button did not hide shell');
    disposeChatBottomTerminal(owner);
    check(disposed === 1 && !owner._bottomTerminal && controls.at(-1).type === 'close', 'Shell cleanup failed');
    return 'PASS: Ctrl+J open/hide/reopen, project cwd, focus, CLI isolation, close button and cleanup';
  })()`));
  clearTimeout(timeout); app.exit(0);
}).catch(error => { console.error(error); app.exit(1); });
