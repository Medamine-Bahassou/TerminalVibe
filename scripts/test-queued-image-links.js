const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '..', 'app.js'), 'utf8');
const ctx = vm.createContext({ escHtml: s => String(s).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;') });
vm.runInContext(source.slice(source.indexOf('  const fmtBytes ='), source.indexOf('  function userTextHtml(')), ctx);
const image = { image: true, name: 'image.png', mention: '@image1', path: '/tmp/image.png', size: 2048, preview: 'data:image/png;base64,abc' };
const text = ctx.queuedMessageTextHtml({ typed: 'Check @image1 please', files: [image] });
assert(text.includes('thr-image-ref') && text.includes('thr-inline-image-icon'));
assert(text.includes('2KB') && text.includes('data:image/png;base64,abc'));
assert(text.includes('data-queue-act="preview"') && text.includes('data-file-i="0"'));
assert(text.indexOf('Check') < text.indexOf('image.png') && text.indexOf('image.png') < text.indexOf('please'));
assert(!text.includes('@image1'));
const restored = ctx.queuedMessageTextHtml({ typed: 'Check @image1', files: [{ ...image, preview: undefined }] });
assert(restored.includes('ph-image') && restored.includes('thr-image-ref'));
assert(ctx.queuedMessageTextHtml({ typed: '', files: [image] }).includes('thr-image-ref'), 'image-only queued messages retain a link');
assert(ctx.queuedMessageTextHtml({ typed: 'No mention', files: [image] }).includes('thr-image-ref'), 'attachments remain accessible after their mention is edited out');
assert(ctx.queuedMessageTextHtml({ typed: '<script>alert(1)</script>', files: [] }).includes('&lt;script&gt;'));
assert(!ctx.chatImageLinkHtml({ ...image, name: '<img>', path: '" onclick="bad' }).includes('title="" onclick='));
const multiple = ctx.queuedMessageTextHtml({ typed: '@note @image1 @image2', files: [{ mention: '@note', name: 'notes.txt' }, image, { ...image, mention: '@image2', name: 'other.png' }] });
assert(multiple.includes('data-file-i="1"') && multiple.includes('data-file-i="2"'));
assert(multiple.includes('notes.txt') && !multiple.includes('@note'));
console.log('Queued image link checks passed');
