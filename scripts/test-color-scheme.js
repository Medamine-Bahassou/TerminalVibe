#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
const start = source.indexOf("  let currentColorScheme = 'dark';");
const end = source.indexOf("  let currentThemeName =", start);
const listeners = {}, choices = ['system', 'light', 'dark'].map(scheme => ({ dataset: { scheme }, addEventListener(event, fn) { this.click = fn; } }));
let applications = 0, saves = 0;
const media = { matches: false, addEventListener(event, fn) { listeners.system = fn; } };
const context = vm.createContext({ window: { matchMedia: () => media },
  document: { querySelectorAll: () => choices }, applyTheme() { applications++; }, saveState() { saves++; }, currentThemeName: 'graphite' });
vm.runInContext(source.slice(start, end), context);
const resolve = vm.runInContext('resolveAppearanceTheme', context);
const dark = { bg: '#101318', fg: '#eeeeee', cursor: '#eeeeee', selection: '#222222', palette: Array(16).fill('#8b9dff'), ui: { accent: '#8b9dff' } };
assert.equal(resolve(dark, true), dark, 'Native dark theme must keep its exact colors');
const light = resolve(dark, false);
assert.notEqual(light.bg, dark.bg);
assert.equal(light.palette.length, 16);
assert.deepEqual(dark.palette, Array(16).fill('#8b9dff'), 'Variants must not mutate saved themes');
const luminance = hex => [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16) / 255).map(v => v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4).reduce((s, v, i) => s + v * [.2126, .7152, .0722][i], 0);
const contrast = (a, b) => { const x = luminance(a), y = luminance(b); return (Math.max(x, y) + .05) / (Math.min(x, y) + .05); };
assert(contrast(light.fg, light.bg) >= 4.5);
assert(contrast(light.ui.accent, light.bg) >= 4.5);
assert(light.palette.every(color => contrast(color, light.bg) >= 3));
assert.equal(resolve(light, false), light, 'An imported light palette stays intact in light mode');
assert(luminance(resolve(light, true).bg) < .1, 'Dark mode adapts light imports');
const controlStart = source.indexOf("  systemColorScheme.addEventListener('change'");
const controlEnd = source.indexOf("  document.getElementById('theme-gallery-import')", controlStart);
vm.runInContext(source.slice(controlStart, controlEnd), context);
choices[0].click();
assert.equal(vm.runInContext('resolvedDarkScheme()', context), false);
media.matches = true; listeners.system();
assert.equal(vm.runInContext('resolvedDarkScheme()', context), true);
assert.equal(applications, 2);
choices[1].click();
assert.equal(vm.runInContext('resolvedDarkScheme()', context), false);
listeners.system();
assert.equal(applications, 3, 'Explicit light mode ignores system changes');
choices[2].click();
assert.equal(vm.runInContext('resolvedDarkScheme()', context), true);
assert.equal(saves, 3, 'Each user scheme choice is persisted');
console.log('PASS: light/dark palette resolution, contrast, immutable theme data, scheme selection, system changes and saving');
