    document.body.append(timer);
    updateScheduleCountdowns(document);
    check(timer.textContent === '00:00:59', 'Live countdown did not show remaining time');
    timer.dataset.countdownAt = String(Date.now() - 1);
    updateScheduleCountdowns(document);
    check(timer.textContent === '00:00:00', 'Countdown must stop at zero');

    open('Clock prompt');
    check(document.activeElement === modeTrigger, 'Scheduler should focus the app dropdown');
    const key = (el, key) => el.dispatchEvent(new KeyboardEvent('keydown', { key, bubbles: true, cancelable: true }));
    key(modeTrigger, 'ArrowDown');
    const menu = modeDropdown.querySelector('[role="listbox"]');
    check(menu.matches(':popover-open') && modeTrigger.getAttribute('aria-expanded') === 'true', 'Schedule types should open in the shared popover');
    key(document.activeElement, 'Escape');
    check(!menu.matches(':popover-open') && scheduleDialog.open && document.activeElement === modeTrigger, 'Escape should close only the dropdown');
    key(modeTrigger, 'ArrowDown');
    key(document.activeElement, 'ArrowDown');
    key(document.activeElement, 'Enter');
    check(mode.value === 'clock' && modeTrigger.textContent.trim() === 'Clock time', 'Keyboard selection should update the clock mode and trigger');
    check(!scheduleClock.hidden && !clockHour.disabled && hours.disabled && minutes.disabled && seconds.disabled, 'Clock mode must show only its clock picker');
    const dial = scheduleClock.querySelector('.chat-clock-face');
    const hour = dial.querySelector('[data-clock-value="2"]');
    hour.focus();
    key(hour, 'ArrowRight');
    check(document.activeElement.dataset.clockValue === '3', 'Arrow keys should move around the clock face');
    hour.click();
    check(clockHour.valueAsNumber === 2 && dial.getAttribute('aria-label') === 'Choose minute', 'Choosing an hour should advance to minutes');
    dial.querySelector('[data-clock-value="30"]').click();
    check(clockMinute.valueAsNumber === 30 && dial.querySelector('[aria-pressed="true"]').dataset.clockValue === '30', 'Selecting a minute should update the time and selection');
    clockMinute.value = '37';
    clockMinute.dispatchEvent(new Event('input', { bubbles: true }));
    check(dial.style.getPropertyValue('--clock-angle') === '222deg', 'Typed minutes should support exact times on the dial');
    clockPeriod.value = 'AM';
    clockHour.value = '12';
    check(readScheduleClockTime() === '00:37', 'Midnight must be represented as 00:37');
    clockHour.value = '02';
    clockPeriod.value = 'PM';
    check(readScheduleClockTime() === '14:37', 'PM should convert to local 24-hour time');
    const today = new Date(2026, 10, 18, 13, 30);
    check(nextScheduleClockTime(+today, '14:30') === +new Date(2026, 10, 18, 14, 30), 'A future clock time should use today');
    check(nextScheduleClockTime(+today, '12:30') === +new Date(2026, 10, 19, 12, 30), 'An earlier clock time should use tomorrow');
    let confirmed = 0, cancelled = 0;
    const openConfirmation = () => showDangerConfirm('Quit TerminalVibe?', 'Running process', 'Quit', () => confirmed++, () => cancelled++);
    clockMinute.focus();
    openConfirmation();
    const rect = clockMinute.getBoundingClientRect();
    const hit = document.elementFromPoint(rect.left + rect.width / 2, rect.top + rect.height / 2);
    check(closeConfirmOverlay.matches(':modal') && closeConfirmOverlay.contains(hit), 'Close confirmation must be above the scheduler');
    check(document.activeElement === closeConfirmCancel, 'The top confirmation must receive focus');
    key(closeConfirmCancel, 'Escape');
    check(cancelled === 1 && confirmed === 0 && !closeConfirmOverlay.open && scheduleDialog.open, 'Escape must dismiss only the confirmation');
    check(document.activeElement === clockMinute && clockMinute.value === '37', 'Returning to the clock must preserve its time and focus');
    openConfirmation();
    closeConfirmOk.click();
