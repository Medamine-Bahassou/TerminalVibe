const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '..', 'app.js'), 'utf8');
const ctx = vm.createContext({ escHtml: s => String(s).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;') });
vm.runInContext(source.slice(source.indexOf('  const tk ='), source.indexOf('  // A file link\'s type icon')), ctx);
const js = ctx.hlDiffLine('+const count = 42; // counter', 'app.js');
assert(js.includes('dl add'));
assert(js.includes('tk-k') && js.includes('tk-n') && js.includes('tk-cm'));
assert(ctx.hlDiffLine('-color: "red";', 'style.css').includes('tk-s'));
assert(ctx.hlDiffLine(' print("hello")', 'main.py').includes('tk-c'));
assert(ctx.hlDiffLine('+{"ok": true}', 'data.json').includes('tk-b'));
assert(ctx.hlDiffLine('+echo "$HOME"', 'run.sh').includes('tk-s'));
const hunk = ctx.hlDiffLine('@@ -1,2 +1,3 @@', 'app.js');
assert(hunk.includes('dl hunk') && !hunk.includes('tk-'));
const unsafe = ctx.hlDiffLine('+const tag = "<script>alert(1)</script>";', 'app.js');
assert(!unsafe.includes('<script>') && unsafe.includes('&lt;script&gt;'));
assert(!ctx.hlDiffLine('+some plain text', 'notes.txt').includes('tk-'));
console.log('Diff highlighting checks passed');
